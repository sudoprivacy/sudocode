//! Typed `password-vault` calls over a Nexus VFS client: one definition shared
//! by the Sudowork `vault.*` capability and native callers such as `scode`'s
//! builtin Vault tools.

use crate::Result;
use nexus_vfs_client::NexusVfsClient;
use prost::Message;
use std::collections::BTreeSet;

/// The upstream `nexus.secrets.v1` protocol.
#[allow(
    clippy::pedantic,
    reason = "Generated by prost from the upstream proto."
)]
pub mod proto {
    include!(concat!(env!("OUT_DIR"), "/nexus.secrets.v1.rs"));
}

/// Call `password-vault.<method>` with a protobuf request and decode the reply.
pub fn call<I: Message, O: Message + Default>(
    client: &NexusVfsClient,
    method: &str,
    input: &I,
) -> Result<O> {
    let bytes = client.call(
        &format!("password-vault.{method}"),
        &input.encode_to_vec(),
        "",
    )?;
    Ok(O::decode(bytes.as_slice())?)
}

/// Version metadata for exactly `namespace`/`key`; never the secret value.
pub fn secret_versions(
    client: &NexusVfsClient,
    namespace: &str,
    key: &str,
) -> Result<Vec<proto::SecretVersion>> {
    let response: proto::ListSecretVersionsResponse = call(
        client,
        "secret_list_versions",
        &proto::ListSecretVersionsRequest {
            namespace: namespace.to_owned(),
            key: key.to_owned(),
        },
    )?;
    Ok(response.versions)
}

/// The keys in `namespace` that hold a live (not deleted) secret. Metadata
/// only, never a value. Absence is read from the listing rather than from an
/// error, because a generic `Call` reports every plugin error, not-found
/// included, as one internal error.
pub fn live_keys(client: &NexusVfsClient, namespace: &str) -> Result<BTreeSet<String>> {
    let response: proto::ListSecretsResponse = call(
        client,
        "secret_list",
        &proto::ListSecretsRequest {
            namespace: Some(namespace.to_owned()),
            include_deleted: false,
        },
    )?;
    Ok(response
        .secrets
        .into_iter()
        .filter(|secret| secret.namespace == namespace && !secret.deleted)
        .map(|secret| secret.key)
        .collect())
}
